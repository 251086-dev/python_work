# Question: what does print() put between values, and at the end of each line?

# My answer, in my own words:
# Between the values, print() puts one space.
# At the end of each line, print() puts a new line,
# so the next print() starts on a new line.

# Source: https://docs.python.org/3/library/functions.html#print

# Three values: print() puts one space between them
print("a", "b", "c")